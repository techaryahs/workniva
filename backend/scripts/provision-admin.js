#!/usr/bin/env node

/**
 * WorkNiva Admin Provisioning Script
 * 
 * Securely provisions or promotes the admin account: admin.workniva@gmail.com
 * Uses the Supabase Service Role Key to manage Auth users and assign the 'admin' role.
 * 
 * Usage:
 *   node scripts/provision-admin.js [optional_password]
 *   ADMIN_PASSWORD=MySecurePass123! npm run provision-admin
 */

const path = require('path');
const crypto = require('crypto');
const dotenv = require('dotenv');

// Resolve .env path
const backendEnvPath = path.resolve(__dirname, '..', '.env');
const rootEnvPath = path.resolve(__dirname, '..', '..', '.env');
dotenv.config({ path: backendEnvPath });
dotenv.config({ path: rootEnvPath });

const { createClient } = require('@supabase/supabase-js');

const SUPABASE_URL = process.env.SUPABASE_URL;
const SUPABASE_SERVICE_ROLE_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY;
const TARGET_ADMIN_EMAIL = (process.env.ADMIN_EMAIL || 'admin.workniva@gmail.com').trim().toLowerCase();

async function provisionAdmin() {
  console.log('====================================================');
  console.log('   WorkNiva Administrator Provisioning Tool');
  console.log('====================================================');
  console.log(`Target Email: ${TARGET_ADMIN_EMAIL}`);

  if (!SUPABASE_URL || !SUPABASE_SERVICE_ROLE_KEY) {
    console.error('\n[ERROR] Missing SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY in .env');
    console.error('Please configure your backend/.env before running this script.');
    process.exit(1);
  }

  // Determine password
  let password = process.argv[2] || process.env.ADMIN_PASSWORD;
  let isAutoGenerated = false;

  if (!password) {
    // Generate a secure 16-character random password
    password = 'Admin_' + crypto.randomBytes(6).toString('base64').replace(/[^a-zA-Z0-9]/g, 'x') + '!9';
    isAutoGenerated = true;
  }

  const supabase = createClient(SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY, {
    auth: {
      autoRefreshToken: false,
      persistSession: false,
    },
  });

  try {
    console.log('\n[1/3] Connecting to Supabase and checking existing users...');
    const { data: usersData, error: listError } = await supabase.auth.admin.listUsers({
      page: 1,
      perPage: 1000,
    });

    if (listError) {
      throw new Error(`Failed to query Supabase Auth users: ${listError.message}`);
    }

    const existingUser = usersData.users.find(
      u => u.email && u.email.toLowerCase() === TARGET_ADMIN_EMAIL
    );

    let userId;

    if (existingUser) {
      userId = existingUser.id;
      console.log(`[2/3] Found existing user account with ID: ${userId}`);

      // If user specified an explicit password or if updating, update password
      if (!isAutoGenerated) {
        console.log('      Updating user password...');
        const { error: updateError } = await supabase.auth.admin.updateUserById(userId, {
          password: password,
          email_confirm: true,
        });
        if (updateError) {
          console.warn(`      Warning: Could not update password: ${updateError.message}`);
        } else {
          console.log('      Password updated successfully.');
        }
      } else {
        console.log('      (Existing password preserved since no new password was specified.)');
      }
    } else {
      console.log(`[2/3] User does not exist. Creating new user account...`);
      const { data: newUser, error: createError } = await supabase.auth.admin.createUser({
        email: TARGET_ADMIN_EMAIL,
        password: password,
        email_confirm: true,
        user_metadata: {
          full_name: 'WorkNiva Administrator',
        },
      });

      if (createError || !newUser?.user) {
        throw new Error(`Failed to create Auth user: ${createError?.message || 'Unknown error'}`);
      }

      userId = newUser.user.id;
      console.log(`      User created successfully with ID: ${userId}`);
    }

    // 3. Upsert admin role in profiles table
    console.log('[3/3] Setting role to "admin" in public.profiles table...');
    const { error: profileError } = await supabase
      .from('profiles')
      .upsert({
        id: userId,
        email: TARGET_ADMIN_EMAIL,
        full_name: 'WorkNiva Administrator',
        role: 'admin',
        updated_at: new Date().toISOString(),
      }, { onConflict: 'id' });

    if (profileError) {
      console.warn(`      Notice: Upsert by ID encountered: ${profileError.message}`);
      console.log('      Attempting fallback update by email...');
      const { error: emailUpdateError } = await supabase
        .from('profiles')
        .update({ role: 'admin' })
        .eq('email', TARGET_ADMIN_EMAIL);

      if (emailUpdateError) {
        throw new Error(`Failed to update profile role: ${emailUpdateError.message}`);
      }
    }

    console.log('\n====================================================');
    console.log('   PROVISIONING COMPLETE: ADMIN ACCESS GRANTED');
    console.log('====================================================');
    console.log(`Email:    ${TARGET_ADMIN_EMAIL}`);
    console.log(`Role:     admin`);
    if (isAutoGenerated && !existingUser) {
      console.log(`Password: ${password}`);
      console.log('>> Please record this temporary password and change it upon first login.');
    } else if (!isAutoGenerated) {
      console.log(`Password: [CONFIGURED AS PROVIDED]`);
    } else {
      console.log(`Password: [PRESERVED EXISTING PASSWORD]`);
    }
    console.log('====================================================\n');

  } catch (err) {
    console.error('\n[PROVISIONING FAILED]:', err.message);
    process.exit(1);
  }
}

provisionAdmin();
